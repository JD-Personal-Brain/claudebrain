"""Refreshes the outside data the agents read: the US 10-year Treasury yield, monthly average,
from the Federal Reserve's H.15 release (public domain), via the datahub.io copy on GitHub
(github.com/datasets/bond-yields-us-10y). A published claude.ai page can't fetch outside
websites, so the build bakes a dated copy into the page and the page shows that date.
Run: python3 scripts/fetch_market.py [path to a local clone of the dataset]"""
import csv, datetime, json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "data", "market.js")
REPO = "https://github.com/datasets/bond-yields-us-10y"

src = sys.argv[1] if len(sys.argv) > 1 else None
if not src:
    src = os.path.join(tempfile.mkdtemp(), "ds")
    subprocess.run(["git", "clone", "-q", "--depth", "1", REPO, src], check=True)
rows = list(csv.reader(open(os.path.join(src, "data", "monthly.csv"))))[1:]
series = [{"month": d[:7], "yield": float(v)} for d, v in rows if v][-24:]
last, six_back = series[-1], series[-7]
market = {
    "name": "US 10-year Treasury yield (monthly average)",
    "publisher": "Federal Reserve, Release H.15 (Selected Interest Rates)",
    "via": REPO,
    "license": "Open Data Commons Public Domain (PDDL 1.0)",
    "fetched": datetime.date.today().isoformat(),
    "series": series,
    "latest": last,
    "sixMonthsBefore": six_back,
    "change6m": round(last["yield"] - six_back["yield"], 2),
}
with open(OUT, "w") as f:
    f.write("// Generated by scripts/fetch_market.py. Do not edit by hand.\n")
    f.write("window.MARKET = " + json.dumps(market, indent=1) + ";\n")
print("wrote", OUT, "latest", last, "change over 6 months", market["change6m"])
